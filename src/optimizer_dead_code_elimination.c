#include "optimizer_dead_code_elimination.h"

#include "ir.h"
#include "ir_free_helpers.h"
#include "optimizer_helpers.h"

#include <stdbool.h>  // bool

bool optimizer_eliminate_dead_code(Ctx* ctx, IrFunctionId function_id) {
  IrFunction* function = &ctx->ir.functions.data[function_id];

  // Check that the function has values to eliminate
  if (function->value_count == 0)
    return false;

  // Count uses of each value
  optimizer_count_value_uses(function, ctx->optimizer.value_data);

  bool changed = false, removed;

  do {
    removed = false;

    // Go through all instructions in all blocks
    for (IrBlockId bid = 0; bid < function->blocks.count; bid++) {
      IrBlock* block = &function->blocks.data[bid];
      for (size_t inst_id = 0; inst_id < block->instructions.count; inst_id++) {
        IrInstruction* instruction = &block->instructions.data[inst_id];

        // AI generated by: Codex (GPT-6.2-sol)
        // Prompt: "Implement all"
        // Changes: Classify removable builtins and retain effects with
        // discarded results.
        if (instruction->result == IR_INVALID_ID ||
            ctx->optimizer.value_data[instruction->result] > 0)
          continue;

        // AI generated by: Codex (GPT-6.2-sol)
        // Prompt: "Implement this change (dont commit  yet)"
        // Changes: Use the shared instruction-level purity check.
        if (!optimizer_is_discardable(instruction)) {
          // Codegen skips FLOAT2INT when the result is IR_INVALID_ID.
          // Keep the destination so the conversion still runs and can fault.
          if (instruction->type == IR_INST_TO_INT)
            continue;

          instruction->result = IR_INVALID_ID;
          changed = true;
          continue;
        }

        // Remove the dead instruction
        ir_free_instruction(instruction);
        array_remove(ctx, &block->instructions, inst_id);
        removed = true;
        changed = true;
      }
    }
  } while (removed);

  return changed;
}
