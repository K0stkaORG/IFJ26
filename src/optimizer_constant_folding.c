bool optimizer_fold_function(Ctx* ctx, IrFunctionId function_id) {
  IrFunction* function = &ctx->ir.functions.data[function_id];

  // AI generated by: Codex (GPT-6.2-sol)
  // Prompt: "Also try to group consecutive prints and optimize statements, which will throw into a throw"
  // Changes: Track blocks that stop at a proven runtime fault.
  bool terminated = false;
  bool modified = false;

  // Iterate over all blocks in the function
  for (IrBlockId bid = 0; bid < function->blocks.count; bid++) {
    IrBlock* block = &function->blocks.data[bid];

    // Iterate over all instructions in the block
    for (size_t inst_id = 0; inst_id < block->instructions.count; inst_id++) {
      IrInstruction* instruction = &block->instructions.data[inst_id];

      // AI generated by: Codex (GPT-6.2-sol)
      // Prompt: "Also try to group consecutive prints and optimize statements, which will throw into a throw"
      // Changes: Preserve the prefix and replace the failing instruction and suffix with an exit.
      IrInt fault = optimizer_known_fault(instruction);
      if (fault != 0) {
        for (size_t i = inst_id; i < block->instructions.count; i++)
          ir_free_instruction(&block->instructions.data[i]);
        block->instructions.count = inst_id;
        ir_set_terminator(
            ctx, function_id, bid,
            (IrBlockTerminator){
                .type = IR_TERMINATOR_EXIT,
                .value.exit_code = {IR_OP_INT32, {.int32_value = fault}},
            });
        terminated = true;
        break;
      }

      IrOperand result;

      // AI generated by: Codex (GPT-6.2-sol)
      // Prompt: "Implement"
      // Changes: Try bounded evaluation for calls whose operands are all known.
      bool folded =
          instruction->type == IR_INST_CALL
              ? optimizer_evaluate_call(&ctx->ir, instruction, &result)
              : optimizer_fold_instruction(ctx, function, instruction, &result);

      if (!folded)
        continue;

      // Replace the value with the constant
      size_t replacements =
          instruction->result == IR_INVALID_ID
              ? 0
              : optimizer_replace_value(ctx, function_id, instruction->result,
                                        result, true);

      // If the result is a string and it's not used anywhere, free it
      if (result.type == IR_OP_STRING && replacements == 0)
        free(result.value.string_value);

      // The instruction was folded, remove it as it's no longer needed
      ir_free_instruction(instruction);
      array_remove(ctx, &block->instructions, inst_id);

      // Decrement the instruction index to account for the removed instruction
      inst_id--;

      // Mark the function as modified
      modified = true;
    }

    // Attempt to fold the block terminator
    modified |= optimizer_fold_branch(&block->terminator);
    modified |=
        optimizer_simplify_negated_branch(ctx, function, &block->terminator);
  }

  // AI generated by: Codex (GPT-6.2-sol)
  // Prompt: "Also try to group consecutive prints and optimize statements, which will throw into a throw"
  // Changes: Remove unreachable uses before later optimizer passes.
  if (terminated)
    optimizer_remove_unreachable_blocks(ctx, function_id);

  return modified || terminated;
}
