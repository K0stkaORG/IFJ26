/**
 * @brief Evaluate a supported builtin call when its literal arguments are
 * sufficient.
 *
 * @param ctx The context.
 * @param inst The instruction to evaluate.
 * @param result The result of the evaluation.
 * @return true if the evaluation was successful, false otherwise.
 */
// AI generated by: Codex (GPT-6.2-sol)
// Prompt: "Implement all"
// Changes: Fold builtins with known results while retaining runtime faults.
static bool optimizer_fold_builtin(Ctx* ctx,
                                   const IrInstruction* inst,
                                   IrOperand* result) {
  const IrOperand* args = inst->operands.call.args;

  const char* string =
      args && args[0].type == IR_OP_STRING ? args[0].value.string_value : NULL;
  size_t length = string ? strlen(string) : 0;

  switch (inst->operands.call.type) {
    case IR_FX_STR_LEN:
      if (!string)
        return false;

      // String length of a known string can be calculated at compile time.
      *result = (IrOperand){IR_OP_INT32, {.int32_value = (IrInt)length}};
      return true;

    case IR_FX_ORD: {
      if (args[1].type != IR_OP_INT32)
        return false;

      IrInt index = args[1].value.int32_value;

      // Ord of a negative index is always -1.
      if (index < 0) {
        *result = (IrOperand){IR_OP_INT32, {.int32_value = -1}};
        return true;
      }

      if (!string)
        return false;

      // Ord of an index out of bounds is always -1.
      if ((size_t)index >= length) {
        *result = (IrOperand){IR_OP_INT32, {.int32_value = -1}};
        return true;
      }

      // Ord of a valid index is the character code at that position.
      *result = (IrOperand){IR_OP_INT32, {.int32_value = string[index]}};
      return true;
    }

    case IR_FX_TO_INT: {
      if (args[0].type != IR_OP_DOUBLE)
        return false;

      // Round the value to the nearest integer and convert to int32.
      double value = trunc(args[0].value.double_value);
      if (!isfinite(value))
        return false;

      *result = (IrOperand){IR_OP_INT32, {.int32_value = (IrInt)value}};
      return true;
    }

    case IR_FX_TO_STR: {
      char buffer[384];
      const char* stringified;

      switch (args[0].type) {
        case IR_OP_INT32:
          snprintf(buffer, sizeof(buffer), "%" PRId64,
                   args[0].value.int32_value);
          stringified = buffer;
          break;

        case IR_OP_DOUBLE: {
          if (!isfinite(args[0].value.double_value))
            return false;

          int length = snprintf(buffer, sizeof(buffer), "%.2f",
                                args[0].value.double_value);

          if (length < 0 || (size_t)length >= sizeof(buffer))
            return false;

          stringified = buffer;
          break;
        }

        case IR_OP_BOOL:
          stringified = args[0].value.bool_value ? "true" : "false";
          break;

        case IR_OP_UNIT:
          stringified = "()";
          break;

        case IR_OP_STRING:
          stringified = args[0].value.string_value;
          break;

        default:
          return false;
      }

      *result = (IrOperand){IR_OP_STRING,
                            {.string_value = copy_string(ctx, stringified)}};
      return true;
    }

    case IR_FX_CHR: {
      if (args[0].type != IR_OP_INT32)
        return false;

      IrInt code = args[0].value.int32_value;
      if (code < 0 || code > 127)
        return false;  // TODO: Throw runtime error 58

      // Convert the integer code to a character and return it as a string.
      char* character = TRY_MALLOC(2);
      character[0] = (char)code;
      character[1] = '\0';
      *result = (IrOperand){IR_OP_STRING, {.string_value = character}};
      return true;
    }

    case IR_FX_STR_SUB: {
      if (!string || args[1].type != IR_OP_INT32 || args[2].type != IR_OP_INT32)
        return false;

      IrInt start = args[1].value.int32_value;
      IrInt end = args[2].value.int32_value;

      if (start < 0 || start > end || (size_t)end > length ||
          (size_t)start >= length)
        return false;  // TODO: Throw runtime error 40

      // Compute the substring and return it as a string.
      size_t count = (size_t)(end - start);
      char* substring = TRY_MALLOC(count + 1);
      memcpy(substring, string + start, count);
      substring[count] = '\0';
      *result = (IrOperand){IR_OP_STRING, {.string_value = substring}};
      return true;
    }

    default:
      return false;
  }
}

/**
 * @brief Tries to fold a constant in the IR
 *
 * @param[in] function The function containing the instruction
 * @param[in] instruction The instruction to fold
 * @param[out] result The result of the fold
 * @return Whether the fold was successful
 */
static bool optimizer_fold_instruction(Ctx* ctx,
                                       IrFunction* function,
                                       IrInstruction* instruction,
                                       IrOperand* result) {
  // Handle each instruction class separately
  switch (ir_get_instruction_class(instruction)) {
    case IR_INST_CLASS_UNARY: {
      IrOperand* operand = &instruction->operands.unary.operand;

      // Handle each unary instruction
      switch (instruction->type) {
        case IR_INST_NOT:
          if (operand->type != IR_OP_BOOL)
            return false;

          *result = (IrOperand){IR_OP_BOOL,
                                {.bool_value = !operand->value.bool_value}};
          return true;

        case IR_INST_INT2DOUBLE:
          if (operand->type != IR_OP_INT32)
            return false;

          *result = (IrOperand){
              IR_OP_DOUBLE,
              {.double_value = (IrDouble)operand->value.int32_value}};
          return true;

        case IR_INST_FLOOR:
          if (operand->type != IR_OP_DOUBLE)
            return false;

          *result = (IrOperand){
              IR_OP_DOUBLE,
              {.double_value = (IrDouble)floor(operand->value.double_value)}};
          return true;

        default:
          return false;
      }
    }

    case IR_INST_CLASS_BINARY: {
      // First try to fold instructions with only one operand being constant
      if (optimizer_fold_identity(instruction, result))
        return true;  // Fold was successful, exit

      IrOperand* left = &instruction->operands.binary.left;
      IrOperand* right = &instruction->operands.binary.right;

      // Handle each binary instruction
      switch (instruction->type) {
        case IR_INST_ADD:
          if (left->type == IR_OP_INT32 && right->type == IR_OP_INT32) {
            *result = (IrOperand){IR_OP_INT32,
                                  {.int32_value = left->value.int32_value +
                                                  right->value.int32_value}};
            return true;
          }

          if (left->type == IR_OP_DOUBLE && right->type == IR_OP_DOUBLE) {
            *result = (IrOperand){IR_OP_DOUBLE,
                                  {.double_value = left->value.double_value +
                                                   right->value.double_value}};
            return true;
          }

          return false;

        case IR_INST_SUB:
          if (left->type == IR_OP_INT32 && right->type == IR_OP_INT32) {
            *result = (IrOperand){IR_OP_INT32,
                                  {.int32_value = left->value.int32_value -
                                                  right->value.int32_value}};
            return true;
          }

          if (left->type == IR_OP_DOUBLE && right->type == IR_OP_DOUBLE) {
            *result = (IrOperand){IR_OP_DOUBLE,
                                  {.double_value = left->value.double_value -
                                                   right->value.double_value}};
            return true;
          }

          return false;

        case IR_INST_MUL:
          if (left->type == IR_OP_INT32 && right->type == IR_OP_INT32) {
            *result = (IrOperand){IR_OP_INT32,
                                  {.int32_value = left->value.int32_value *
                                                  right->value.int32_value}};
            return true;
          }

          if (left->type == IR_OP_DOUBLE && right->type == IR_OP_DOUBLE) {
            *result = (IrOperand){IR_OP_DOUBLE,
                                  {.double_value = left->value.double_value *
                                                   right->value.double_value}};
            return true;
          }

          return false;

        case IR_INST_IDIV:
          if (left->type != IR_OP_INT32 || right->type != IR_OP_INT32)
            return false;

          if (right->value.int32_value == 0)
            return false;  // TODO: optimize as throw

          *result = (IrOperand){IR_OP_INT32,
                                {.int32_value = left->value.int32_value /
                                                right->value.int32_value}};
          return true;

        case IR_INST_DIV:
          if (left->type != IR_OP_DOUBLE || right->type != IR_OP_DOUBLE)
            return false;

          if (right->value.double_value == 0)
            return false;  // TODO: optimize as throw

          *result = (IrOperand){IR_OP_DOUBLE,
                                {.double_value = left->value.double_value /
                                                 right->value.double_value}};
          return true;

        // Handle all comparison operations at once
        // 0. (check for special case with 2 IR_OP_VALUE operands)
        // 1. Calculate the "order" of the operands
        // 2. Based on the instruction type and the order, return true or false
        case IR_INST_EQ:
        case IR_INST_NE:
        case IR_INST_LT:
        case IR_INST_LE:
        case IR_INST_GT:
        case IR_INST_GE: {
          if (left->type != right->type)
            return false;  // TODO: optimize as throw

          // If both operands are the same value
          if (left->type == IR_OP_VALUE && left->value.id == right->value.id) {
            IrInstruction* definition =
                optimizer_find_definition(function, left->value.id);

            // They will always be equal if they are not doubles
            if (definition != NULL && definition->result_type != IR_DOUBLE) {
              *result = (IrOperand){
                  .type = IR_OP_BOOL,
                  .value.bool_value = instruction->type == IR_INST_EQ ||
                                      instruction->type == IR_INST_LE ||
                                      instruction->type == IR_INST_GE};

              return true;
            }
          }

          int order = 0;

          // Calculate the order of the operands based on their type
          // (1 if left > right, 0 if equal, -1 if left < right)
          switch (left->type) {
            case IR_OP_INT32:
              order = (left->value.int32_value > right->value.int32_value) -
                      (left->value.int32_value < right->value.int32_value);
              break;

            case IR_OP_DOUBLE:
              // AI generated by: Codex (GPT-6.2-sol)
              // Prompt: "Implement all"
              // Changes: Match interpreter ordering for NaN, including
              // equality.
              if (isnan(left->value.double_value) ||
                  isnan(right->value.double_value)) {
                *result = (IrOperand){
                    IR_OP_BOOL,
                    {.bool_value = instruction->type == IR_INST_NE}};
                return true;
              }
              order = (left->value.double_value > right->value.double_value) -
                      (left->value.double_value < right->value.double_value);
              break;

            case IR_OP_STRING:
              order =
                  strcmp(left->value.string_value, right->value.string_value);
              break;

            case IR_OP_BOOL:
              if (instruction->type != IR_INST_EQ &&
                  instruction->type != IR_INST_NE)
                return false;  // TODO: check spec

              order = left->value.bool_value - right->value.bool_value;
              break;

            default:
              return false;
          }

          bool value = false;

          // Fold the comparison based on the instruction type and the order of
          // the operands
          switch (instruction->type) {
            case IR_INST_EQ:
              value = order == 0;
              break;
            case IR_INST_NE:
              value = order != 0;
              break;
            case IR_INST_LT:
              value = order < 0;
              break;
            case IR_INST_LE:
              value = order <= 0;
              break;
            case IR_INST_GT:
              value = order > 0;
              break;
            case IR_INST_GE:
              value = order >= 0;
              break;

            default:
              return false;
          }

          *result = (IrOperand){IR_OP_BOOL, {.bool_value = value}};
          return true;
        }

        case IR_INST_CONCAT: {
          if (left->type != IR_OP_STRING || right->type != IR_OP_STRING)
            return false;

          size_t left_len = strlen(left->value.string_value);
          size_t right_len = strlen(right->value.string_value);

          // Allocate memory for the concatenated string
          char* concat = TRY_MALLOC(left_len + right_len + 1);

          // Copy the string values into the concatenated string
          memcpy(concat, left->value.string_value, left_len);
          memcpy(concat + left_len, right->value.string_value, right_len);
          concat[left_len + right_len] = '\0';

          *result = (IrOperand){IR_OP_STRING, {.string_value = concat}};

          return true;
        }

        default:
          return false;
      }
    } break;

    // Function calls
    case IR_INST_CLASS_CALL:
      // AI generated by: Codex (GPT-6.2-sol)
      // Prompt: "Implement all"
      // Changes: Apply builtin folding to calls with a result.
      return instruction->result != IR_INVALID_ID &&
             optimizer_fold_builtin(ctx, instruction, result);

    // Store and load remain and they cant be folded
    default:
      break;
  }

  return false;
}

bool optimizer_fold_function(Ctx* ctx, IrFunctionId function_id) {
  IrFunction* function = &ctx->ir.functions.data[function_id];

  bool modified = false;

  // Iterate over all blocks in the function
  for (IrBlockId bid = 0; bid < function->blocks.count; bid++) {
    IrBlock* block = &function->blocks.data[bid];

    // Iterate over all instructions in the block
    for (size_t inst_id = 0; inst_id < block->instructions.count; inst_id++) {
      IrInstruction* instruction = &block->instructions.data[inst_id];

      IrOperand result;

      // Try to fold the instruction
      if (!optimizer_fold_instruction(ctx, function, instruction, &result))
        continue;  // Unable to fold, go to next instruction

      // Replace the value with the constant
      size_t replacements = optimizer_replace_value(
          ctx, function_id, instruction->result, result, true);

      // If the result is a string and it's not used anywhere, free it
      if (result.type == IR_OP_STRING && replacements == 0)
        free(result.value.string_value);

      // The instruction was folded, remove it as it's no longer needed
      ir_free_instruction(instruction);
      array_remove(ctx, &block->instructions, inst_id);

      // Decrement the instruction index to account for the removed instruction
      inst_id--;

      // Mark the function as modified
      modified = true;
    }

    // Attempt to fold the block terminator
    modified |= optimizer_fold_branch(&block->terminator);
    modified |=
        optimizer_simplify_negated_branch(ctx, function, &block->terminator);
  }

  // Return whether the function was modified
  return modified;
}
