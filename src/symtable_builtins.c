#include "symtable_builtins.h"
#include <stddef.h>
#include <string.h>
#include "ctx.h"
#include "ir.h"
#include "symtable.h"

static void symtable_create_builtin(Ctx* ctx,
                                    Symtable* table,
                                    char* name,
                                    IrFunctionType fx_type,
                                    IrType return_type,
                                    size_t param_count,
                                    IrType* params) {
  SymtableData data = {0};
  data.symbol_type = SYMBOL_FUNCTION;
  data.ir_type = return_type;
  data.ir_index = fx_type;  // index in ir.h enum of built-in functions
  data.param_count = param_count;

  if (param_count > 0) {
    IrType* param_arr = TRY_MALLOC(sizeof(IrType) * param_count);
    memcpy(param_arr, params, sizeof(IrType) * param_count);
    data.param_types = param_arr;
  } else {
    data.param_types = NULL;
  }

  symtable_insert(ctx, table, name, data);
}

void symtable_builtins_populate(Ctx* ctx, Symtable* global_table) {
  if (global_table == NULL)
    return;

  // AI generated by: Antigravity / Gemini 3.8 Flash
  // Prompt: "Add into symtable_builtins_populate calls to
  // symtable_create_builtin for each IFJ26 built-in function according to ir.h"
  // Changes: Populated global symtable with all 11 built-in functions defined
  // in ir.h.
  // 1. readInt() -> Int
  symtable_create_builtin(ctx, global_table, "readInt", IR_FX_READ_INT, IR_INT,
                          0, NULL);
  // 2. readDouble() -> Double
  symtable_create_builtin(ctx, global_table, "readDouble", IR_FX_READ_DOUBLE,
                          IR_DOUBLE, 0, NULL);
  // 3. readBoolean() -> Bool
  symtable_create_builtin(ctx, global_table, "readBoolean", IR_FX_READ_BOOL,
                          IR_BOOL, 0, NULL);
  // 4. readLine() -> String
  symtable_create_builtin(ctx, global_table, "readLine", IR_FX_READ_LINE,
                          IR_STRING, 0, NULL);
  // 5. toInt(Double) -> Int
  symtable_create_builtin(ctx, global_table, "toInt", IR_FX_TO_INT, IR_INT, 1,
                          (IrType[]){IR_DOUBLE});
  // 6. toStr(term: any) -> String
  symtable_create_builtin(ctx, global_table, "toStr", IR_FX_TO_STR, IR_STRING,
                          1, (IrType[]){IR_UNIT});
  // 7. print(term: any) -> Unit
  symtable_create_builtin(ctx, global_table, "print", IR_FX_PRINT, IR_UNIT, 1,
                          (IrType[]){IR_UNIT});
  // 8. strLength(String) -> Int
  symtable_create_builtin(ctx, global_table, "strLength", IR_FX_STR_LEN, IR_INT,
                          1, (IrType[]){IR_STRING});
  // 9. subStr(String, Int, Int) -> String
  symtable_create_builtin(ctx, global_table, "subStr", IR_FX_STR_SUB, IR_STRING,
                          3, (IrType[]){IR_STRING, IR_INT, IR_INT});
  // 10. ord(String, Int) -> Int
  symtable_create_builtin(ctx, global_table, "ord", IR_FX_ORD, IR_INT, 2,
                          (IrType[]){IR_STRING, IR_INT});
  // 11. chr(Int) -> String
  symtable_create_builtin(ctx, global_table, "chr", IR_FX_CHR, IR_STRING, 1,
                          (IrType[]){IR_INT});
}
