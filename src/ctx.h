/**
 * @brief Shared memory and error context for the IFJ26 compiler
 */
typedef struct Ctx {
  // Exit code of the program
  ExitCode exit_code;

  // Stack of error frames for scoped error handling
  CtxErrorFrame* error_frame;

  // Flags for the compiler
  Flags flags;

  // Abstract syntax tree of the program
  AstNode* ast;

  // Global symbol table
  Symtable global_symtable;

  // Intermediate representation of the program
  IrProgram ir;
} Ctx;

