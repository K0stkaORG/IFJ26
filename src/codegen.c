// Code structure

static void cg_print_nl(FILE* out) {
  fputs("\n", out);
}

static void cg_print_ws(FILE* out) {
  fputs(" ", out);
}

static void cg_print_preamble(FILE* out) {
  fputs(".IFJcode26", out);
  cg_print_nl(out);
}

// Data types

static void cg_print_int(FILE* out, IrInt value) {
  fprintf(out, "int@%lld", value);
}

static void cg_print_float(FILE* out, IrDouble value) {
  fprintf(out, "float@%a", value);
}

static void cg_print_bool(FILE* out, IrBool value) {
  fputs(value ? "bool@true" : "bool@false", out);
}

static void cg_print_nil(FILE* out) {
  fputs("nil@nil", out);
}

static void cg_print_string(FILE* out, char* str) {
  fputs("string@", out);
  for (size_t i = 0; i < strlen(str); i++) {
    if (str[i] <= 32 || str[i] == 35 || str[i] == 92) {
      fprintf(out, "\\%03u", (unsigned char)str[i]);
    } else {
      fputc(str[i], out);
    }
  }
}

// Operands

static void cg_print_localframe_val(FILE* out, size_t id) {
  fprintf(out, "LF@val_%zu", id);
}

static void cg_print_localframe_slot(FILE* out, size_t id) {
  fprintf(out, "LF@slot_%zu", id);
}

static void cg_print_tempframe_arg(FILE* out, size_t id) {
  fprintf(out, "TF@arg_%zu", id);
}

static void cg_print_localframe_arg(FILE* out, size_t id) {
  fprintf(out, "LF@arg_%zu", id);
}

static void cg_print_operand(FILE* out, IrOperand* op) {
  switch (op->type) {
    case IR_OP_VALUE:
      cg_print_localframe_val(out, op->value.id);
      break;
    case IR_OP_INT32:
      cg_print_int(out, op->value.int32_value);
      break;
    case IR_OP_DOUBLE:
      cg_print_float(out, op->value.double_value);
      break;
    case IR_OP_BOOL:
      cg_print_bool(out, op->value.bool_value);
      break;
    case IR_OP_STRING:
      cg_print_string(out, op->value.string_value);
      break;
    case IR_OP_UNIT:
      cg_print_nil(out);
      break;
  }
}

// Built-in functions

// AI generated by: Antigravity / Gemini 3.8 Flash
// Prompt: "Implement helper function cg_print_builtin_call in codegen.c that
// creates a temporary frame, passes call arguments into TF@arg_<id>, calls the
// built-in function label $$builtin_<name>, and moves the return value from
// TF@%ret into LF@val_<result> if a result is expected." Changes: Add helper
// function cg_print_builtin_call for emitting built-in runtime function calls
// with argument passing and return value retrieval.
static void cg_print_builtin_call(FILE* out,
                                  const char* name,
                                  IrInstruction* inst) {
  fputs("CREATEFRAME\n", out);

  for (size_t i = 0; i < inst->operands.call.arg_count; i++) {
    fputs("DEFVAR ", out);
    cg_print_tempframe_arg(out, i);
    cg_print_nl(out);

    fputs("MOVE ", out);
    cg_print_tempframe_arg(out, i);
    cg_print_ws(out);
    cg_print_operand(out, &inst->operands.call.args[i]);
    cg_print_nl(out);
  }

  fputs("CALL $$builtin_", out);
  fputs(name, out);
  cg_print_nl(out);

  if (inst->result != IR_INVALID_ID) {
    fputs("MOVE ", out);
    cg_print_localframe_val(out, inst->result);
    fputs(" TF@%ret\n", out);
  }
}

static void cg_print_builtin(FILE* out, IrInstruction* inst) {
  switch (inst->operands.call.type) {
    // inline
    case IR_FX_STR_LEN:
      fputs("STRLEN ", out);
      cg_print_localframe_val(out, inst->result);
      cg_print_ws(out);
      cg_print_operand(out, &inst->operands.call.args[0]);
      cg_print_nl(out);
      break;
    case IR_FX_TO_INT:
      fputs("FLOAT2INT ", out);
      cg_print_localframe_val(out, inst->result);
      cg_print_ws(out);
      cg_print_operand(out, &inst->operands.call.args[0]);
      cg_print_nl(out);
      break;
    case IR_FX_CHR:
      fputs("INT2CHAR ", out);
      cg_print_localframe_val(out, inst->result);
      cg_print_ws(out);
      cg_print_operand(out, &inst->operands.call.args[0]);
      cg_print_nl(out);
      break;

    // calls
    case IR_FX_PRINT:
      cg_print_builtin_call(out, "print", inst);
      break;
    case IR_FX_READ_INT:
      cg_print_builtin_call(out, "readInt", inst);
      break;
    case IR_FX_READ_DOUBLE:
      cg_print_builtin_call(out, "readDouble", inst);
      break;
    case IR_FX_READ_BOOL:
      cg_print_builtin_call(out, "readBool", inst);
      break;
    case IR_FX_READ_LINE:
      cg_print_builtin_call(out, "readLine", inst);
      break;
    case IR_FX_TO_STR:
      cg_print_builtin_call(out, "toStr", inst);
      break;
    case IR_FX_STR_SUB:
      cg_print_builtin_call(out, "subStr", inst);
      break;
    case IR_FX_ORD:
      cg_print_builtin_call(out, "ord", inst);
      break;

    case IR_FX_USER:  // silence warning
      break;
  }
}

// Instructions

static void cg_print_unary_inst(FILE* out, char* opcode, IrInstruction* inst) {
  fputs(opcode, out);
  cg_print_ws(out);
  cg_print_localframe_val(out, inst->result);
  cg_print_ws(out);
  cg_print_operand(out, &inst->operands.unary.operand);
  cg_print_nl(out);
}

static void cg_print_binary_inst(FILE* out, char* opcode, IrInstruction* inst) {
  fputs(opcode, out);
  cg_print_ws(out);
  cg_print_localframe_val(out, inst->result);
  cg_print_ws(out);
  cg_print_operand(out, &inst->operands.binary.left);
  cg_print_ws(out);
  cg_print_operand(out, &inst->operands.binary.right);
  cg_print_nl(out);
}

static void cg_print_not_result(FILE* out, size_t result) {
  fputs("NOT ", out);
  cg_print_localframe_val(out, result);
  cg_print_ws(out);
  cg_print_localframe_val(out, result);
  cg_print_nl(out);
}

static void cg_generate_instruction(Ctx* ctx, FILE* out, IrInstruction* inst) {
  switch (inst->type) {
    case IR_INST_ADD:
      cg_print_binary_inst(out, "ADD", inst);
      break;
    case IR_INST_SUB:
      cg_print_binary_inst(out, "SUB", inst);
      break;
    case IR_INST_MUL:
      cg_print_binary_inst(out, "MUL", inst);
      break;
    case IR_INST_DIV:
      cg_print_binary_inst(out, "DIV", inst);
      break;
    case IR_INST_IDIV:
      cg_print_binary_inst(out, "IDIV", inst);
      break;
    // AI generated by: Codex / gpt-6.1-sol
    // Prompt: "Fixed missing semantic analyze, fix the error"
    // Changes: Floor negative fractions and preserve the Double result type.
    case IR_INST_FLOOR: {
      static size_t floor_label = 0;
      size_t label = floor_label++;
      cg_print_unary_inst(out, "FLOAT2INT", inst);
      fputs("INT2FLOAT ", out);
      cg_print_localframe_val(out, inst->result);
      cg_print_ws(out);
      cg_print_localframe_val(out, inst->result);
      cg_print_nl(out);
      fputs("LT LF@%floor_negative ", out);
      cg_print_operand(out, &inst->operands.unary.operand);
      cg_print_ws(out);
      cg_print_localframe_val(out, inst->result);
      cg_print_nl(out);
      fprintf(out, "JUMPIFEQ $$%%floor_%zu LF@%%floor_negative bool@false\n", label);
      fputs("SUB ", out);
      cg_print_localframe_val(out, inst->result);
      cg_print_ws(out);
      cg_print_localframe_val(out, inst->result);
      fputs(" float@0x1p+0\n", out);
      fprintf(out, "LABEL $$%%floor_%zu\n", label);
      break;
    }
    case IR_INST_CONCAT:
      cg_print_binary_inst(out, "CONCAT", inst);
      break;
    case IR_INST_NOT:
      cg_print_unary_inst(out, "NOT", inst);
      break;
    case IR_INST_INT2DOUBLE:
      cg_print_unary_inst(out, "INT2FLOAT", inst);
      break;
    case IR_INST_EQ:
      cg_print_binary_inst(out, "EQ", inst);
      break;
    case IR_INST_LT:
      cg_print_binary_inst(out, "LT", inst);
      break;
    case IR_INST_GT:
      cg_print_binary_inst(out, "GT", inst);
      break;
    case IR_INST_NE:
      cg_print_binary_inst(out, "EQ", inst);
      cg_print_not_result(out, inst->result);
      break;
    case IR_INST_LE:
      cg_print_binary_inst(out, "GT", inst);
      cg_print_not_result(out, inst->result);
      break;
    case IR_INST_GE:
      cg_print_binary_inst(out, "LT", inst);
      cg_print_not_result(out, inst->result);
      break;
    case IR_INST_LOAD:
      fputs("MOVE ", out);
      cg_print_localframe_val(out, inst->result);
      cg_print_ws(out);
      cg_print_localframe_slot(out, inst->operands.load.source);
      cg_print_nl(out);
      break;
    case IR_INST_STORE:
      fputs("MOVE ", out);
      cg_print_localframe_slot(out, inst->operands.store.target);
      cg_print_ws(out);
      cg_print_operand(out, &inst->operands.store.source);
      cg_print_nl(out);
      break;
    case IR_INST_CALL:
      if (inst->operands.call.type == IR_FX_USER) {
        fputs("CREATEFRAME", out);
        cg_print_nl(out);

        for (size_t i = 0; i < inst->operands.call.arg_count; i++) {
          fputs("DEFVAR ", out);
          cg_print_tempframe_arg(out, i);
          cg_print_nl(out);

          fputs("MOVE ", out);
          cg_print_tempframe_arg(out, i);
          cg_print_ws(out);
          cg_print_operand(out, &inst->operands.call.args[i]);
          cg_print_nl(out);
        }

        fputs("CALL $$", out);
        fputs(ctx->ir.functions.data[inst->operands.call.id].name, out);
        cg_print_nl(out);

        if (inst->result != IR_INVALID_ID) {
          fputs("MOVE ", out);
          cg_print_localframe_val(out, inst->result);
          fputs(" TF@%ret", out);
          cg_print_nl(out);
        }
      } else {
        cg_print_builtin(out, inst);
      }
      break;
  }
}

// Blocks

static void cg_print_block_label(FILE* out, char* fn_name, size_t block_id) {
  fprintf(out, "$%s$b%zu", fn_name, block_id);
}

static void cg_generate_block(Ctx* ctx,
                              FILE* out,
                              IrFunction* fn,
                              size_t block_id,
                              IrBlock* block) {
  fputs("LABEL ", out);
  cg_print_block_label(out, fn->name, block_id);
  cg_print_nl(out);

  for (size_t i = 0; i < block->instructions.count; i++) {
    IrInstruction* inst = &block->instructions.data[i];
    cg_generate_instruction(ctx, out, inst);
  }

  switch (block->terminator.type) {
    case IR_TERMINATOR_EXIT:
      fputs("EXIT ", out);
      cg_print_operand(out, &block->terminator.value.exit_code);
      cg_print_nl(out);
      break;
    case IR_TERMINATOR_JUMP:
      if (block->terminator.value.jump_target != IR_INVALID_ID) {
        fputs("JUMP ", out);
        cg_print_block_label(out, fn->name,
                             block->terminator.value.jump_target);
        cg_print_nl(out);
      }
      break;
    case IR_TERMINATOR_RETURN:
      if (fn->return_type != IR_UNIT) {
        fputs("MOVE LF@%ret ", out);
        cg_print_operand(out, &block->terminator.value.return_value);
        cg_print_nl(out);
      }
      fputs("POPFRAME", out);
      cg_print_nl(out);
      fputs("RETURN", out);
      cg_print_nl(out);
      break;
    case IR_TERMINATOR_CONDITIONAL:
      fputs("JUMPIFEQ ", out);
      cg_print_block_label(
          out, fn->name,
          block->terminator.value.conditional_target.true_target);
      cg_print_ws(out);
      cg_print_operand(out,
                       &block->terminator.value.conditional_target.condition);
      cg_print_ws(out);
      cg_print_bool(out, true);
      cg_print_nl(out);
      fputs("JUMP ", out);
      cg_print_block_label(
          out, fn->name,
          block->terminator.value.conditional_target.false_target);
      cg_print_nl(out);
      break;
  }
}

// Functions

static void cg_generate_function(Ctx* ctx, FILE* out, IrFunction* fn) {
  fputs("LABEL $$", out);
  fputs(fn->name, out);
  cg_print_nl(out);
  fputs("PUSHFRAME", out);
  cg_print_nl(out);

  if (fn->return_type != IR_UNIT) {
    fputs("DEFVAR LF@%ret", out);
    cg_print_nl(out);
  }

  // AI generated by: Codex / gpt-6.1-sol
  // Prompt: "Fixed missing semantic analyze, fix the error"
  // Changes: Reserve a scratch Boolean for floor emission.
  bool needs_floor = false;
  for (size_t b = 0; b < fn->blocks.count; b++)
    for (size_t i = 0; i < fn->blocks.data[b].instructions.count; i++)
      needs_floor |= fn->blocks.data[b].instructions.data[i].type == IR_INST_FLOOR;
  if (needs_floor)
    fputs("DEFVAR LF@%floor_negative\n", out);

  for (size_t i = 0; i < fn->value_count; i++) {
    fputs("DEFVAR ", out);
    cg_print_localframe_val(out, i);
    cg_print_nl(out);
  }

  for (size_t i = 0; i < fn->slots.count; i++) {
    fputs("DEFVAR ", out);
    cg_print_localframe_slot(out, i);
    cg_print_nl(out);
  }

  for (size_t i = 0; i < fn->parameter_count; i++) {
    fputs("MOVE ", out);
    cg_print_localframe_slot(out, i);
    cg_print_ws(out);
    cg_print_localframe_arg(out, i);
    cg_print_nl(out);
  }

  if (fn->entrypoint != IR_INVALID_ID && fn->entrypoint != 0) {
    fputs("JUMP ", out);
    cg_print_block_label(out, fn->name, fn->entrypoint);
    cg_print_nl(out);
  }

  for (size_t i = 0; i < fn->blocks.count; i++) {
    IrBlock* block = &fn->blocks.data[i];
    cg_generate_block(ctx, out, fn, i, block);
  }

  fputs("POPFRAME", out);
  cg_print_nl(out);
  fputs("RETURN", out);
  cg_print_nl(out);
}

// Generator

void cg_generate(FILE* out, Ctx* ctx) {
  cg_print_preamble(out);

  if (ctx->ir.entrypoint != IR_INVALID_ID) {
    fputs("CREATEFRAME", out);
    cg_print_nl(out);
    fputs("CALL $$", out);
    fputs(ctx->ir.functions.data[ctx->ir.entrypoint].name, out);
    cg_print_nl(out);
    fputs("EXIT ", out);
    cg_print_int(out, 0);
    cg_print_nl(out);
  }

  // AI generated by: Antigravity / Gemini 3.8 Flash
  // Prompt: "Update cg_generate to loop through all function calls and if it's
  // built-in function, call cg_generate_builtin(out, IrFunctionType)." Changes:
  // Loop through all instructions in all functions and emit each called
  // built-in function at most once via cg_generate_builtin.
  bool generated_builtins[IR_FX_CHR + 1] = {false};
  for (size_t i = 0; i < ctx->ir.functions.count; i++) {
    IrFunction* fn = &ctx->ir.functions.data[i];
    for (size_t j = 0; j < fn->blocks.count; j++) {
      IrBlock* block = &fn->blocks.data[j];
      for (size_t k = 0; k < block->instructions.count; k++) {
        IrInstruction* inst = &block->instructions.data[k];
        if (inst->type == IR_INST_CALL &&
            inst->operands.call.type != IR_FX_USER) {
          IrFunctionType fx_type = inst->operands.call.type;
          if (!generated_builtins[fx_type]) {
            cg_generate_builtin(out, fx_type);
            generated_builtins[fx_type] = true;
          }
        }
      }
    }
  }

  for (size_t i = 0; i < ctx->ir.functions.count; i++) {
    IrFunction* fn = &ctx->ir.functions.data[i];
    cg_generate_function(ctx, out, fn);
  }
}
