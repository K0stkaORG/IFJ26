// include guard
#ifndef LEXER_H
#define LEXER_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include "array.h"
typedef struct Ctx Ctx;  // Forward declaration to avoid circular includes

/**
 * @brief Definition of lexical tokens
 */
typedef enum {
  IDENT,

  // Keywords
  AT_MAIN,
  IMPORT,
  DEF,
  VAL,
  VAR,
  RETURN,
  IF,
  THEN,
  ELSE,
  WHILE,
  DO,

  // Types
  TYPE_INT,
  TYPE_DOUBLE,
  TYPE_STRING,
  TYPE_UNIT,
  TYPE_LIST,

  // LISTS
  L_BRACKET,
  R_BRACKET,

  // CONTROL, BOOLTHEN
  FOR,
  TYPE_BOOL,
  BOOL_TRUE,
  BOOL_FALSE,

  // Values
  NUMBER_INT,
  NUMBER_DOUBLE,
  UNIT,

  // Strings
  STRING,
  TRIPLE_STRING,

  // INTERPOLATEDS
  S_STRING_START,
  S_STRING_END,
  TRIPLE_S_STRING_START,
  TRIPLE_S_STRING_END,
  DOLLAR_EXPRESSION_START,
  DOLLAR_EXPRESSION_END,

  // Operators
  OPERATOR_PLUS,
  OPERATOR_MINUS,
  OPERATOR_MULTIPLY,
  OPERATOR_DIVIDE,
  OPERATOR_CONCAT,

  // Comparisons
  ASSIGN,
  COMPARISON_EQ,
  COMPARISON_NEQ,
  COMPARISON_G,
  COMPARISON_L,
  COMPARISON_GE,
  COMPARISON_LE,

  // BOOLTHEN
  BOOL_AND,
  BOOL_OR,
  BOOL_NEG,

  // Punctuation
  L_PAREN,
  R_PAREN,
  COMMA,
  PERIOD,
  COLON,
  SEMICOLON,

  // CONTROL
  CONTROL_ARROW,

  // Whitespace
  INDENT,
  EOL_TOKEN,
  WHITESPACE,
  EOF_TOKEN
} TokenType;

/**
 * @brief Union defining the value of a token
 */
typedef union {
  int64_t integer;
  double decimal;
  char* text;
} TokenValue;

/**
 * @brief Enum defining the value type of a token
 */
typedef enum {
  INTEGER,
  DECIMAL,
  TEXT,
} TokenValueType;

/**
 * @brief structure defining the tokens
 */
typedef struct {
  TokenType type;
  TokenValue value;
  TokenValueType value_type;
  size_t line;
  size_t column;
} Token;

/**
 * @brief Array type for lexer buffer
 */
ARRAY_TYPE(LexerByteBuffer, unsigned char);

/**
 * @brief Array type for lexer buffer
 */
ARRAY_TYPE(LexerStack, int);

typedef struct {
  LexerByteBuffer buffer;
  LexerStack stack;
  LexerStack saved_stack;
  size_t line;
  size_t column;
  size_t cursor;
  int indent_flag;
  int indent_level;
  // AI generated by: Zed / GPT-6.2 Sol
  // Prompt: "Fix this bug: Code after a multiline block comment. The lexer
  // needs to reject code after the closing */ on the same physical line when
  // the block comment is multiline. Preserve the forum-approved case of another
  // comment following it." Changes: Remember the physical line on which code is
  // forbidden.
  size_t multiline_comment_end_line;
} LexerCtx;

/**
 * @brief Returns next token and deletes from the reel
 *
 * @return Next token
 */
Token next_token(Ctx* ctx);

#endif /* LEXER_H */
