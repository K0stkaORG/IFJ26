/**
 * @brief Run local cleanup to a fixed point for each function.
 *
 * @param ctx The context of the compiler.
 */
// Run local passes to a fixed point because each rewrite can expose new folds
// and dead code.
// AI generated by: Codex (GPT-6.2-sol)
// Prompt: "Implement all"
// Changes: Run local cleanup before and after growing the IR.
static void optimize_functions(Ctx* ctx) {
  // Iteratively optimize functions until no more changes are made
  for (IrFunctionId fid = 0; fid < ctx->ir.functions.count; fid++) {
    size_t iterations = 0;
    bool changed;

    do {
      iterations++;

      changed = optimizer_fold_function(ctx, fid);
      changed |= optimizer_eliminate_dead_code(ctx, fid);
      changed |= optimizer_forward_stores(ctx, fid);
      changed |= optimizer_remove_unreachable_blocks(ctx, fid);
      changed |= optimizer_remove_unused_stores(ctx, fid);
      changed |= optimizer_simplify_jumps(ctx, fid);
      changed |= optimizer_forward_cfg_constants(ctx, fid);
      changed |= optimizer_reuse_expressions(ctx, fid);
    } while (changed);

    // Print debug info
    iterations--;
    if (iterations > 0)
      DEBUG("Optimization of function %s took %zu iterations",
            ctx->ir.functions.data[fid].name, iterations);
    else
      DEBUG("Failed to optimize function %s", ctx->ir.functions.data[fid].name);
  }
}

// AI generated by: Codex (GPT-6.2-sol)
// Prompt: "Implement all"
// Changes: Run bounded call and loop passes between local cleanup rounds.
void optimize_ir(Ctx* ctx) {
  // Prepare the optimizer context
  optimizer_prepare(ctx);

  // Remove unreachable functions (before optimizing, to avoid optimizing
  // unreachable functions)
  size_t removed = optimizer_remove_unreachable_functions(ctx);
  if (removed > 0)
    DEBUG("Removed (pre-optimization) %zu unreachable functions", removed);

  optimize_functions(ctx);

  // Remove unreachable functions (also after optimizing, to remove functions
  // that are no longer reachable)
  removed = optimizer_remove_unreachable_functions(ctx);
  if (removed > 0)
    DEBUG("Removed (post-optimization) %zu unreachable functions", removed);
}

void optimizer_init(OptimizerCtx* optimizer) {
  // Initialize buffer sizes to zero
  optimizer->sizes.values = 0;
  optimizer->sizes.blocks = 0;
  optimizer->sizes.functions = 0;

  // Initialize value data buffer to NULL
  optimizer->value_data = NULL;

  // Initialize blocks data buffer to NULL
  optimizer->blocks = NULL;

  // Initialize block ID map to NULL
  optimizer->block_data = NULL;

  // Initialize function data buffer to NULL
  optimizer->functions = NULL;

  // Initialize function ID map to NULL
  optimizer->function_id_map = NULL;

  // Initialize CFG facts buffer to NULL
  optimizer->cfg_facts = NULL;
}

void optimizer_prepare(Ctx* ctx) {
  OptimizerCtx* o_ctx = &ctx->optimizer;

  // Compute the maximum number of value uses across all functions
  for (IrFunctionId fid = 0; fid < ctx->ir.functions.count; fid++)
    if (ctx->ir.functions.data[fid].value_count > o_ctx->sizes.values)
      o_ctx->sizes.values = ctx->ir.functions.data[fid].value_count;

  // Allocate value uses buffer
  o_ctx->value_data = TRY_MALLOC(o_ctx->sizes.values * sizeof(size_t));

  // Compute the maximum number of blocks across all functions (so that we can
  // reuse the same buffer across all functions)
  for (IrFunctionId fid = 0; fid < ctx->ir.functions.count; fid++)
    if (ctx->ir.functions.data[fid].blocks.count > o_ctx->sizes.blocks)
      o_ctx->sizes.blocks = ctx->ir.functions.data[fid].blocks.count;

  // Allocate block data buffer
  o_ctx->blocks = TRY_MALLOC(o_ctx->sizes.blocks * sizeof(bool));

  // Allocate block ID map
  o_ctx->block_data = TRY_MALLOC(o_ctx->sizes.blocks * sizeof(size_t));

  o_ctx->sizes.functions = ctx->ir.functions.count;

  // Allocate function data buffer
  o_ctx->functions = TRY_MALLOC(o_ctx->sizes.functions * sizeof(bool));

  // Allocate function ID map
  o_ctx->function_id_map = TRY_MALLOC(o_ctx->sizes.functions * sizeof(size_t));
}

void optimizer_free(OptimizerCtx* optimizer) {
  // Reset sizes to 0
  optimizer->sizes.values = 0;
  optimizer->sizes.blocks = 0;
  optimizer->sizes.functions = 0;

  // Free memory
  free(optimizer->value_data);
  optimizer->value_data = NULL;

  free(optimizer->blocks);
  optimizer->blocks = NULL;

  free(optimizer->block_data);
  optimizer->block_data = NULL;

  free(optimizer->functions);
  optimizer->functions = NULL;

  free(optimizer->function_id_map);
  optimizer->function_id_map = NULL;

  free(optimizer->cfg_facts);
  optimizer->cfg_facts = NULL;
}
